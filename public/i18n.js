const KEY = 'riuh.lang';
export const isLang = v => v === 'id' || v === 'en';

export function preferredLang() {
  const saved = store.get(KEY);
  if (isLang(saved)) return saved;
  return (navigator.language || '').toLowerCase().startsWith('id') ? 'id' : 'en';
}

export function rememberLang(lang) {
  if (isLang(lang)) store.set(KEY, lang);
}

/** t(lang, 'key', ...args): teks biasa atau hasil fungsi berparameter */
export function t(lang, key, ...args) {
  const v = (STR[lang] || STR.id)[key];
  return typeof v === 'function' ? v(...args) : v;
}

export const fmt = (lang, n) => Number(n).toLocaleString(lang === 'id' ? 'id-ID' : 'en-US');
